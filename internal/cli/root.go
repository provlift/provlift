// BuildInfo is stamped in at link time.
type BuildInfo struct {
	Version string
	Commit  string
	Date    string
}

// NewRootCommand assembles the command tree.
func NewRootCommand(build BuildInfo) *cobra.Command {
	g := &globalOptions{}

	root := &cobra.Command{
		Use:   "provlift",
		Short: "Discover and upgrade Terraform provider dependencies",
		Long: `provlift inventories the Terraform providers used across a repository,
reports the upgrades available for each one, and applies patch, minor or major
upgrades safely.

Version constraints are edited in place with a minimum diff; dependency lock
content is generated by Terraform so its checksums stay correct. Failed refreshes
may restore the original lock bytes unchanged.`,
		SilenceUsage:  true,
		SilenceErrors: true,
	}

	g.bind(root)

	root.AddCommand(
		newListCommand(g),
		newCheckCommand(g),
		newDriftCommand(g),
		newUpgradeCommand(g),
		newValidateCommand(g),
		newVersionCommand(g, build),
	)
	return root
}

func ExecuteContext(ctx context.Context, root *cobra.Command, arguments []string) error {
	root.SetArgs(arguments)
	command, err := root.ExecuteContextC(ctx)
	if err == nil {
		return nil
	}
	var coded *ExitCodeError
	if errors.As(err, &coded) {
		return err
	}
	if command != nil && command.Name() == "upgrade" {
		flags := pflag.NewFlagSet("upgrade output", pflag.ContinueOnError)
		flags.SetOutput(io.Discard)
		flags.ParseErrorsWhitelist.UnknownFlags = true
		register := func(flag *pflag.Flag) {
			if flags.Lookup(flag.Name) != nil {
				return
			}
			flags.StringP(flag.Name, flag.Shorthand, flag.DefValue, "")
			flags.Lookup(flag.Name).NoOptDefVal = flag.NoOptDefVal
		}
		command.Flags().VisitAll(register)
		command.InheritedFlags().VisitAll(register)
		_ = flags.Parse(arguments)
		jsonValue, _ := flags.GetString("json")
		jsonOutput, _ := strconv.ParseBool(jsonValue)
		if jsonOutput {
			dryRunValue, _ := flags.GetString("dry-run")
			dryRun, _ := strconv.ParseBool(dryRunValue)
			if writeErr := report.JSON(root.OutOrStdout(), upgradeResult(dryRun)); writeErr != nil {
				return exitWith(ExitError, writeErr)
			}
		}
	}
	return exitWith(ExitError, err)
}

func newVersionCommand(g *globalOptions, build BuildInfo) *cobra.Command {
	return &cobra.Command{
		Use:   "version",
		Short: "Print the provlift version",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			info := map[string]string{
				"version": build.Version,
				"commit":  build.Commit,
				"date":    build.Date,
				"go":      runtime.Version(),
				"os_arch": runtime.GOOS + "_" + runtime.GOARCH,
			}
			if g.jsonOut {
				return writeJSON(g, info)
			}
			_, err := fmt.Fprintf(g.stdout(), "provlift %s (commit %s, built %s, %s %s/%s)\n",
				build.Version, build.Commit, build.Date, runtime.Version(), runtime.GOOS, runtime.GOARCH)
			return err
		},
	}
}
